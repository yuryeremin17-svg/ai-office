#!/usr/bin/env bash
# ============================================================================
# lib.sh — общие куски болванки. Подключать: . "$SCRIPT_DIR/lib.sh"
#
# Появился 27.07 по итогам прогона №2: одни и те же две вещи (разбор версии
# движка и чтение его логов) были размазаны по install.sh, update.sh,
# rollback.sh и watchdog.sh — и разъехались. Разбор версии терял суффикс
# сборки, из-за чего установщик пугал клиента ложной тревогой, а еженедельное
# обновление считало бы версию «разошедшейся» каждую неделю.
# ============================================================================

# Где движок пишет логи. journalctl --user на сервере пуст (проверено прогоном
# 26.07), настоящие логи — файлы в /tmp; переменную можно переопределить в тестах.
ENGINE_LOG_DIR="${ENGINE_LOG_DIR:-/tmp/openclaw}"

# Дождаться, пока apt освободится. Свежезагруженный сервер обычно занят
# автообновлениями (unattended-upgrades), и любая наша установка пакета падает
# на замке dpkg — ловилось на живом стенде 27.07.
apt_wait() {
  local limit="${1:-300}" waited=0
  while fuser /var/lib/dpkg/lock-frontend >/dev/null 2>&1 \
     || fuser /var/lib/apt/lists/lock >/dev/null 2>&1 \
     || fuser /var/lib/dpkg/lock >/dev/null 2>&1; do
    [ "$waited" -ge "$limit" ] && return 1
    sleep 3
    waited=$((waited + 3))
  done
  return 0
}

# Версия движка целиком, ВМЕСТЕ с суффиксом сборки: «2026.7.1-2», а не «2026.7.1».
# Без суффикса сравнение с пином всегда ложно-отрицательное:
#   ENGINE_VERSION=2026.7.1-2, а `grep -oE '[0-9]{4}\.[0-9]+\.[0-9]+'` даёт 2026.7.1
#   → «пин не встал» при фактически вставшем пине (прогон 27.07).
engine_version() {
  openclaw --version 2>/dev/null | grep -oE '[0-9]{4}\.[0-9]+\.[0-9]+(-[0-9]+)?' | head -1
}

# Свежий хвост логов движка: и journald (если вдруг пишет), и файлы.
recent_engine_log() {
  journalctl --user -u openclaw-gateway --since "10 min ago" --no-pager 2>/dev/null
  ls -1t "$ENGINE_LOG_DIR"/*.log 2>/dev/null | head -2 | while read -r f; do
    tail -300 "$f" 2>/dev/null
  done
}

# То же, но пригодное для человека: только ошибки и предупреждения, только текст
# сообщения. Движок пишет JSON-строками — сырой хвост в нашем логе поддержке
# бесполезен, в нём тонут собственные строки сторожа (замечание прогона 27.07).
compact_engine_log() {
  recent_engine_log \
    | grep -iE '"level":"?(error|warn)|\bERROR\b|\bWARN\b' \
    | sed -E 's/.*"(msg|message)":"([^"]*)".*/\2/' \
    | cut -c1-200 \
    | tail -"${1:-8}"
}
