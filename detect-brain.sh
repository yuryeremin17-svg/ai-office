#!/usr/bin/env bash
# ============================================================================
# detect-brain.sh — какой «мозг» ставить офису. Печатает: global | ru
#
# Раньше установщик спрашивал человека: «Вы в России?». Вопрос неправильный:
# доступ к моделям зависит не от того, где человек живёт, а от того, отдаёт ли
# OpenRouter модели ЕГО ключу (у части аккаунтов Claude/GPT/Gemini закрыты
# по региону аккаунта с мая 2026). Руководитель из Москвы с зарубежным
# аккаунтом отвечал «да» и получал слабый мозг; с российским аккаунтом отвечал
# «нет» — и офис вставал на модель, к которой у него нет доступа: установка
# прошла, а бот молчит.
#
# Поэтому не спрашиваем никого, а спрашиваем сам OpenRouter — пробуем ту самую
# модель, которую пропишем в конфиг. Ровно это делает бот-установщик
# (installer-bot: validators.detectBrainTier) — теперь оба пути ведут себя одинаково.
#
# Стоимость пробы: один токен на выходе, доли цента.
#
# Аргументы: [ключ OpenRouter]  (или переменная OPENROUTER_API_KEY)
# Печатает в stdout: global | ru   (пояснения — в stderr, чтобы не мешали)
# ============================================================================
set -uo pipefail

KEY="${1:-${OPENROUTER_API_KEY:-}}"

# Слаги обязаны совпадать с моделями в install.sh (Шаг 1) — проверяем то,
# что реально будем ставить.
MODEL_GLOBAL="google/gemini-2.5-flash"
MODEL_RU="deepseek/deepseek-v4-flash"

note() { printf '%s\n' "$1" >&2; }

probe() {  # печатает HTTP-код или 000 при сетевом сбое
  curl -s -o /dev/null -m 20 -w '%{http_code}' \
    https://openrouter.ai/api/v1/chat/completions \
    -H "Authorization: Bearer ${KEY}" \
    -H "Content-Type: application/json" \
    -d "{\"model\":\"$1\",\"max_tokens\":1,\"messages\":[{\"role\":\"user\",\"content\":\"ping\"}]}" \
    2>/dev/null || echo 000
}

if [ -z "$KEY" ]; then
  note "  (ключ не передан — ставлю обычный мозг)"
  echo global
  exit 0
fi

code="$(probe "$MODEL_GLOBAL")"

case "$code" in
  2*)
    note "  ✓ сильные модели доступны вашему ключу — ставлю Gemini + Claude"
    echo global
    ;;
  403|404)
    # Модель закрыта этому ключу — почти всегда региональное ограничение аккаунта.
    code2="$(probe "$MODEL_RU")"
    case "$code2" in
      2*) note "  ✓ Gemini вашему ключу закрыт (ограничение OpenRouter) — ставлю DeepSeek: дешевле и доступен" ;;
      *)  note "  ⚠ ваш ключ пока не открывает ни одну из наших моделей (проверьте баланс и настройки Privacy на openrouter.ai). Ставлю DeepSeek — офис заговорит, как только доступ появится" ;;
    esac
    echo ru
    ;;
  *)
    # Сеть, 429, 5xx — не повод давать клиенту слабый мозг: молчание сервиса
    # не значит отказ. Ставим обычный, сменить модель можно одной командой.
    note "  (не удалось спросить OpenRouter, ответ «$code» — ставлю обычный мозг, сменить можно позже командой /model)"
    echo global
    ;;
esac
