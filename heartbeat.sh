#!/usr/bin/env bash
# ============================================================================
# heartbeat.sh — «пульс жив». Зовётся частым таймером (каждые 15 мин).
# Пингует внешний датчик (healthchecks.io) ТОЛЬКО если офис реально работает.
# Датчик сам поднимет тревогу в наш Телеграм, если пинг не пришёл вовремя.
# Пока HEARTBEAT_URL не задан в .office-env — тихо ничего не делает (крючок).
# ============================================================================
set -euo pipefail
ENVF="$HOME/.openclaw/.office-env"
[ -f "$ENVF" ] && . "$ENVF" || true

# датчик не настроен — выходим тихо (пульс выключен)
[ -n "${HEARTBEAT_URL:-}" ] || exit 0

# содержательный чек: пингуем ТОЛЬКО если шлюз реально активен.
# Если офис лёг — намеренно НЕ пингуем, чтобы датчик поднял тревогу по таймауту.
state=$(systemctl --user is-active openclaw-gateway 2>/dev/null || echo down)
[ "$state" = "active" ] || exit 0

curl -fsS -m 10 "$HEARTBEAT_URL" >/dev/null 2>&1 || true
